package sanberdir.java_lesson;

public class Lesson {

    public static void main(String[] arguments) {
        /* ОПЕРАТОРЫ ПРИСВАИВАНИЯ */
// Эти операторы используются для присваивания значений переменным
// и выполнения математических операций с одновременным присваиванием

// Обычное присваивание =
// Создаем переменную mana (мана) и присваиваем ей начальное значение 100
        int mana = 100;
// Выводим текущее значение маны: Mana: 100
        System.out.println("Mana: " + mana);

// СЛОЖЕНИЕ С ПРИСВАИВАНИЕМ +=
// Увеличиваем значение маны на 20 единиц
// Эквивалентно записи: mana = mana + 20;
        mana += 20;
// Теперь мана равна 100 + 20 = 120
// Выводим: Mana: 120
        System.out.println("Mana: " + mana);

// ИНКРЕМЕНТ (увеличение на 1) ++
// Увеличиваем значение маны на 1 единицу
// Эквивалентно записи: mana += 1; или mana = mana + 1;
        mana++;
// Теперь мана равна 120 + 1 = 121
// Выводим: Mana: 121
        System.out.println("Mana: " + mana);

// ВЫЧИТАНИЕ С ПРИСВАИВАНИЕМ -=
// Уменьшаем значение маны на 60 единиц
// Эквивалентно записи: mana = mana - 60;
        mana -= 60;
// Теперь мана равна 121 - 60 = 61
// Выводим: Mana: 61
        System.out.println("Mana: " + mana);

// ДЕКРЕМЕНТ (уменьшение на 1) --
// Уменьшаем значение маны на 1 единицу
// Эквивалентно записи: mana -= 1; или mana = mana - 1;
        mana--;
// Теперь мана равна 61 - 1 = 60
// Выводим: Mana: 60
        System.out.println("Mana: " + mana);

// УМНОЖЕНИЕ С ПРИСВАИВАНИЕМ *=
// Увеличиваем значение маны в 2 раза
// Эквивалентно записи: mana = mana * 2;
        mana *= 2;
// Теперь мана равна 60 * 2 = 120
// Выводим: Mana: 120
        System.out.println("Mana: " + mana);

// ДЕЛЕНИЕ С ПРИСВАИВАНИЕМ /=
// Уменьшаем значение маны в 4 раза
// Эквивалентно записи: mana = mana / 4;
        mana /= 4;
// Теперь мана равна 120 / 4 = 30
// Выводим: Mana: 30
        System.out.println("Mana: " + mana);

// ДЕЛЕНИЕ ПО МОДУЛЮ С ПРИСВАИВАНИЕМ %=
// Находим остаток от деления маны на 2
// Эквивалентно записи: mana = mana % 2;
        mana %= 2;
// Остаток от деления 30 на 2 равен 0 (30 ÷ 2 = 15 без остатка)
// Выводим: Mana: 0
        System.out.println("Mana: " + mana);
    }
}