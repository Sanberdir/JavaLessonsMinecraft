package sanberdir.java_lesson;

public class Lesson {

    public static void main(String[] arguments) {
        /*
         * ДЕМОНСТРАЦИЯ РАБОТЫ С ЦЕЛЫМИ ЧИСЛАМИ И МАТЕМАТИЧЕСКИМИ ОПЕРАЦИЯМИ В JAVA
         * Для новичков в программировании - разберем основные математические операции
         */

        // Объявляем и инициализируем две переменные
        int a = 100;
        int b = 200;

        // -------------------------------
        // ОСНОВНЫЕ АРИФМЕТИЧЕСКИЕ ОПЕРАЦИИ
        // -------------------------------

        // СЛОЖЕНИЕ
        int summa = a + b;
        System.out.println("Сумма: " + summa + " результат."); // Результат: 300

        // ВЫЧИТАНИЕ
        int sub = a - b;
        System.out.println("Вычитание: " + sub); // Результат: -100

        // УМНОЖЕНИЕ
        int multi = a * b;
        System.out.println("Умножение: " + multi); // Результат: 20000

        // ДЕЛЕНИЕ
        double division = (double) a / b;
        System.out.println("Деление 100.0/200: " + division); // Результат: 0 (целочисленное деление! или 0.5 при double)

        division = b / (double) a;
        System.out.println("Деление 200/100.0: " + division); // Результат: 2

        // ВАЖНО! ДЕЛЕНИЕ НА НОЛЬ ЗАПРЕЩЕНО
        // Раскомментируйте следующую строку, чтобы увидеть ошибку:
        // division = b / 0;
        // System.out.println("Деление: " + division); // Будет ошибка ArithmeticException

        // -------------------------------
        // ОПЕРАЦИЯ ОСТАТОК ОТ ДЕЛЕНИЯ (МОДУЛЬ)
        // -------------------------------

        // Полезно для проверки четности чисел, циклов и т.д.
        int remainder = 100 % 2;
        System.out.println("Остаток от 100/2: " + remainder); // 0 (четное число)

        remainder = 100 % 3;
        System.out.println("Остаток от 100/3: " + remainder); // 1

        remainder = 100 % 4;
        System.out.println("Остаток от 100/4: " + remainder); // 0

        // -------------------------------
        // ПОЛЕЗНЫЕ МАТЕМАТИЧЕСКИЕ МЕТОДЫ ИЗ КЛАССА Math
        // -------------------------------

        // МОДУЛЬ ЧИСЛА (абсолютное значение)
        System.out.println("Абсолютное значение: " + Math.abs(-100)); // 100

        // ОКРУГЛЕНИЕ ЧИСЕЛ
        System.out.println("Округление вверх: " + Math.ceil(1.23));    // 2.0 (всегда вверх)
        System.out.println("Математическое округление: " + Math.round(1.23));     // 1 (стандартное округление)
        System.out.println("Округление вниз: " + Math.floor(1.83));     // 1.0 (всегда вниз)

        // ПОИСК МИНИМУМА И МАКСИМУМА
        System.out.println("Минимум: " + Math.min(a, b)); // 10
        System.out.println("Максимум: " + Math.max(37, 750)); // 750

        /*
         * КЛЮЧЕВЫЕ МОМЕНТЫ ДЛЯ ЗАПОМИНАНИЯ:
         * 1. При делении целых чисел результат тоже целый (дробная часть отбрасывается)
         * 2. Деление на ноль вызывает ошибку
         * 3. Оператор % полезен для проверки четности и многих других задач
         * 4. Класс Math содержит множество полезных математических функций
         *
         * ПРАКТИЧЕСКОЕ ЗАДАНИЕ:
         * Попробуйте изменить значения переменных a и b и посмотреть на результаты!
         */
    }
}