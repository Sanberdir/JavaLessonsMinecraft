package sanberdir.java_lesson;

import java.util.Scanner;

public class Lesson {

    public static void main(String[] arguments) {
        /* ЦИКЛЫ (FOR И WHILE) */
// Циклы используются для многократного выполнения одного и того же блока кода

// Проблема: нужно вывести все числа от 0 до 99...
        System.out.println(0);
        System.out.println(2);
        System.out.println(4);
        System.out.println(6);
        System.out.println(8);
        System.out.println(10);
// Это очень неэффективно - пришлось бы писать 100 строк кода!

// Другая проблема: вывести високосные годы между 1000 и 2000!
        System.out.println(1000);
        System.out.println(1004);
        System.out.println(1008);
//... это займет вечность! Придется писать ~250 строк кода

        System.out.println("-------");

// ЦИКЛ FOR - используется когда известно точное количество повторений

// Цикл for состоит из трех частей:
// 1. Инициализация: int i = 0 (создаем счетчик)
// 2. Условие: i < 100 (пока истинно - выполняем цикл)
// 3. Шаг: i++ (увеличиваем счетчик после каждой итерации)
        for (int i = 0; i < 15; i++) {
            // Этот блок выполнится 100 раз
            // i будет принимать значения от 0 до 99
            System.out.println(i);
        }

        System.out.println("-------");

// Цикл for с условием внутри - выводим только нечетные числа
        for(int i = 0; i < 24; i++) {
            if (i % 2 != 0) {  // Проверяем, не делится ли число на 2 без остатка
                System.out.println(i);  // Выводим только нечетные числа
            }
        }

// Цикл для високосных годов между 1000 и 2000
        for(int i = 1000; i <= 2000; i++) {
            // Условие для високосного года:
            // год делится на 4 И (НЕ делится на 100 ИЛИ делится на 400)
            if(i % 4 == 0 && (i % 100 != 0 || i % 400 == 0)) {
                // System.out.println(i);  // Закомментировано, чтобы не засорять вывод
            }
        }

        System.out.println("-------");

// ЦИКЛ WHILE - используется когда неизвестно точное количество повторений,
// но известно условие продолжения

        int health = 10;
// Цикл while выполняется ПОКА условие истинно
        while (health > 0) {
            System.out.println("Player still alive with " + health + " HP");
            health--;  // Уменьшаем здоровье на 1 каждый цикл
            // Когда health станет 0, условие health > 0 станет ложным и цикл остановится
        }

        System.out.println("-------");

// Демонстрация операторов break и continue в цикле
        health = 10;
        while (health > 0) {
            health--;  // Сначала уменьшаем здоровье

            if (health == 6) {
                continue;  // Пропускаем оставшуюся часть цикла и переходим к следующей итерации
                // Когда health = 6, код ниже не выполнится, сразу перейдем к проверке условия
            }

            if (health == 2) {
                break;  // Немедленно прерываем выполнение цикла
                // Цикл завершится досрочно, даже если условие health > 0 еще истинно
            }

            System.out.println("Player still alive with " + health + " HP");
            // Этот вывод не выполнится для health = 6 (из-за continue)
            // и для health <= 2 (из-за break)
        }
    }
}