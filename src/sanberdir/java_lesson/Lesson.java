package sanberdir.java_lesson;

import java.util.Scanner;

public class Lesson {

    public static void main(String[] arguments) {
        /* ТЕРНАРНЫЙ ОПЕРАТОР */
// Тернарный оператор - это короткая форма записи условного оператора if-else
// Формат: условие ? значение_если_истина : значение_если_ложь

// Создаем переменную здоровья и строку статуса
        int health = 3;
        String status = "";

// Выводим начальный статус (пустая строка)
        System.out.println("Каков ваш статус? " + status); // Выведет: Каков ваш статус?

// Традиционный способ с if-else
        if (health > 0) {
            status = "Жив";
        } else {
            status = "Мёртв";
        }
        System.out.println("Каков ваш статус? " + status); // Выведет: Каков ваш статус? Жив

// Сбрасываем статус для демонстрации тернарного оператора
        status = "";

// Тернарный оператор - делает то же самое что if-else выше, но в одну строку
// Читается как: "Если health > 0, то присвоить 'Жив', иначе присвоить 'Мёртв'"
        status = health > 0 ? "Жив" : "Мёртв";
        System.out.println("Каков ваш статус? " + status); // Выведет: Каков ваш статус? Жив

// Дополнительные примеры тернарного оператора:

// Пример 1: Проверка на четность числа
        int number = 7;
        String evenOrOdd = (number % 2 == 0) ? "чётное" : "нечётное";
        System.out.println("Число " + number + " является " + evenOrOdd); // Выведет: Число 7 является нечётное

// Пример 2: Определение максимального из двух чисел
        int a = 10, b = 15;
        int max = (a > b) ? a : b;
        System.out.println("Максимальное число: " + max); // Выведет: Максимальное число: 15

// Пример 3: Проверка возможности голосования
        int age = 17;
        String canVote = (age >= 18) ? "может голосовать" : "не может голосовать";
        System.out.println("Человек возрастом " + age + " лет " + canVote); // Выведет: Человек возрастом 17 лет не может голосовать
    }
}