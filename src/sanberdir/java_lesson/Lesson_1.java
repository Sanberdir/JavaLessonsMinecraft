/**
 * Урок 2: Типы данных и переменные в Java
 *
 * Этот класс демонстрирует базовые концепции работы с переменными
 * и типами данных в языке программирования Java.
 *
 * Класс содержит метод main - точку входа в программу,
 * где выполняются все демонстрационные примеры.
 */
package sanberdir.java_lesson;

public class Lesson_1 {
    /**
     * Главный метод программы - точка входа при запуске приложения
     *
     * @param arguments аргументы класса String (используются в этом уроке)
     *
     * В этом методе мы изучаем:
     * 1. Переменные в Java
     * 2. Объявление и инициализацию переменных
     * 3. Основные типы данных в Java
     */
    public static void main(String[] arguments) {
        /* DATA TYPES & VARIABLES */

        // Одиночный комментарий - всё что после двух слешей игнорируется компилятором
        // Hello I am a comment

        /*
         * Многострочный комментарий - полезен для подробных объяснений
         * And I am a multiline Comment!
         * I can come in quite handy for explaining stuff!
         */

        /* Variables (Переменные) */

        // Объявление переменной: datatype name_of_variable;
        // Инициализация: datatype name_of_variable = value_of_variable;
        // (Объявление + Присвоение значения)

        /* DATA TYPES (ТИПЫ ДАННЫХ) */

        // ЦЕЛЫЕ ЧИСЛА (хранят целые числа, включая отрицательные)
        // int - диапазон от -2147483648 до 2147483647
        int points;        // Объявление переменной без значения
        points = 100;      // Присвоение значения
        int x = -69;       // Инициализация (объявление + присвоение)

        // ДРОБНЫЕ ЧИСЛА (числа с плавающей точкой)
        float pi = 3.14159265F;  // float - 32 бита, требует 'f' в конце
        double e = 2.718281828;  // double - 64 бита, более точный

        // ВАЖНО: При работе с дробными числами возможны погрешности вычислений
        // из-за ограниченной точности представления в двоичной системе
        // Научная нотация: 314159265 * 10^-8

        // ЛОГИЧЕСКИЕ ЗНАЧЕНИЯ (истина или ложь)
        boolean likedVideo = true;   // true - истина
        boolean subscribed = true;   // false - ложь

        // СИМВОЛЫ И СТРОКИ
        char grade = 'B';           // char - один символ в одинарных кавычках
        String name = "Sanberdir";  // String - строка символов в двойных кавычках

        // ОСОБЕННОСТИ:
        // - char использует 16 бит (Unicode)
        // - String не примитивный тип, а класс
        // - Строки в Java неизменяемы (immutable)
    }
}